#!/usr/bin/env python3
"""
Builds js/data.js from the official PokemonTCG/pokemon-tcg-data dump.

Source: https://github.com/PokemonTCG/pokemon-tcg-data (MIT-licensed card *data*).
Card names, HP, types, attacks, rarities, artists and flavour text are the real
printed values. Artwork is loaded at runtime from the public card-image CDNs with
a bundled official-artwork fallback (see build_art.py).

Output is a compact positional-array format to keep the payload small; the
schema is mirrored by decodeCard() in js/data-decode.js.
"""
import json, os, re, sys, glob

RAW = os.environ.get("RAW_DIR", "raw")
OUT = os.path.join(os.path.dirname(__file__), "..", "js", "data.js")

# Sets shipped with the game, in unlock order.
SETS = ["base1", "xy1", "sm1", "swsh7", "swsh12pt5",
        "sv3pt5", "sv4pt5", "sv8", "sv8pt5", "sv10", "me1"]

# Printed rarity -> game tier. Tier drives pull odds, FX, audio and value.
TIER = {
    "Common": 0, "Uncommon": 1,
    "Rare": 2, "Rare Holo": 2,
    "Double Rare": 3, "Rare Holo V": 3, "Rare Holo GX": 3, "Rare Holo EX": 3,
    "Rare Holo VSTAR": 3, "Rare Holo VMAX": 3, "ACE SPEC Rare": 3, "Radiant Rare": 3,
    "Ultra Rare": 4, "Rare Ultra": 4, "Illustration Rare": 4, "Shiny Rare": 4,
    "Special Illustration Rare": 5, "Rare Rainbow": 5, "Shiny Ultra Rare": 5,
    "Hyper Rare": 6, "Rare Secret": 6, "Mega Hyper Rare": 6,
}

ENERGY = {"Grass":"G","Fire":"R","Water":"W","Lightning":"L","Psychic":"P",
          "Fighting":"F","Darkness":"D","Metal":"M","Fairy":"Y","Dragon":"N",
          "Colorless":"C"}

def clip(s, n):
    if not s:
        return ""
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[:n - 1].rstrip() + "…"

def enc_types(types):
    return "".join(ENERGY.get(t, "C") for t in (types or []))

def build_card(c, set_id):
    rarity = c.get("rarity") or "Common"
    tier = TIER.get(rarity)
    if tier is None:                       # unknown/promo rarity -> treat as rare
        tier = 2
    atks = []
    for a in (c.get("attacks") or [])[:2]:
        atks.append([
            clip(a.get("name"), 26),
            enc_types(a.get("cost")),
            (a.get("damage") or "").strip(),
            clip(a.get("text"), 88),
        ])
    weak = ""
    if c.get("weaknesses"):
        w = c["weaknesses"][0]
        weak = ENERGY.get(w.get("type"), "") + (w.get("value") or "")
    dex = (c.get("nationalPokedexNumbers") or [0])[0]
    subs = c.get("subtypes") or []
    # Trainers and Energy carry their effect in `rules`; the first entry is the
    # card's own text (later entries are the generic "you may play as many..."
    # reminders), which is what actually belongs on the card face.
    rules = ""
    if c.get("rules"):
        rules = clip(c["rules"][0], 150)
    ability = []
    if c.get("abilities"):
        a0 = c["abilities"][0]
        ability = [clip(a0.get("name"), 26), clip(a0.get("text"), 110),
                   clip(a0.get("type"), 14)]
    return [
        c["id"],
        clip(c.get("name"), 34),
        enc_types(c.get("types")),
        (c.get("hp") or ""),
        tier,
        rarity,
        c.get("number") or "",
        clip(c.get("artist"), 24),
        clip(c.get("flavorText"), 108),
        atks,
        weak,
        len(c.get("retreatCost") or []),
        dex,
        1 if c.get("supertype") == "Pokémon" else (2 if c.get("supertype") == "Trainer" else 3),
        clip(" ".join(subs), 30),
        rules,
        ability,
    ]

def main():
    out_sets, out_cards, total = [], {}, 0
    for sid in SETS:
        path = os.path.join(RAW, sid + ".json")
        if not os.path.exists(path):
            print("missing", path, file=sys.stderr); continue
        cards = json.load(open(path))
        built = [build_card(c, sid) for c in cards]
        # A pack needs at least one card of tiers 0/1/2 to be openable.
        tiers = {b[4] for b in built}
        if not {0, 1}.issubset(tiers):
            print("skipping (no commons)", sid, file=sys.stderr); continue
        out_cards[sid] = built
        out_sets.append(sid)
        total += len(built)
        print(f"{sid:10s} {len(built):4d} cards")

    payload = {"sets": out_sets, "cards": out_cards}
    body = json.dumps(payload, separators=(",", ":"), ensure_ascii=False)
    header = (
        "/* Generated by tools/build_data.py - do not edit by hand.\n"
        " * Real Pokemon TCG card data from github.com/PokemonTCG/pokemon-tcg-data.\n"
        " * Positional schema (see js/data-decode.js):\n"
        " *  0 id  1 name  2 types  3 hp  4 tier  5 rarity  6 number  7 artist\n"
        " *  8 flavor  9 attacks[[name,cost,damage,text]]  10 weakness  11 retreat\n"
        " * 12 dex  13 supertype(1=Pokemon,2=Trainer,3=Energy)  14 subtypes\n"
        " */\n"
    )
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(header + "window.CARD_DB = " + body + ";\n")
    print(f"\n{total} cards across {len(out_sets)} sets -> {OUT} "
          f"({os.path.getsize(OUT)/1024:.0f} KB)")

if __name__ == "__main__":
    main()
